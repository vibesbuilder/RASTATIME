def _vlc_plugin_dir() -> Optional[Path]:
    """Return the VLC plugins directory, or None if VLC is not installed."""
    try:
        from playout.engine_vlc.probe import _find_dll
        dll = _find_dll()
        if dll is None:
            return None
        return dll.parent / "plugins"
    except Exception:
        return None


def _plugin_exists(relative_glob: str) -> bool:
    """
    Return True if at least one plugin file matching *relative_glob* exists
    under the VLC plugins directory.

    relative_glob is relative to the plugins dir, e.g.
    ``"access_output/libaccess_output_shout_plugin.dll"``
    or ``"codec/libtwolame*"``.
    """
    pdir = _vlc_plugin_dir()
    if pdir is None:
        return False
    return bool(list(pdir.glob(relative_glob)))


