def _make_wav(duration: float = 0.5, sample_rate: int = 44100) -> Path:
    """Generate a short sine-wave WAV file in a temp location."""
    n = int(sample_rate * duration)
    samples = [
        int(32767 * math.sin(2 * math.pi * 440 * i / sample_rate))
        for i in range(n)
    ]
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as f:
        path = Path(f.name)
    with wave.open(str(path), "w") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(sample_rate)
        wf.writeframes(struct.pack(f"<{n}h", *samples))
    return path


def _play_sout(wav_path: Path, sout_chain: str, timeout: float = 15.0) -> bool:
    """
    Transcode *wav_path* through *sout_chain* using libVLC.

    Returns True when MediaPlayerEndReached fires within *timeout* seconds.
    Cleans up the player and instance on exit.
    """
    import vlc

    instance = vlc.Instance(
        "--no-video",
        "--quiet",
        "--aout=adummy",   # no local audio output during tests
    )
    try:
        media = instance.media_new(wav_path.as_uri())
        media.add_option(f"sout={sout_chain}")
        media.add_option("sout-all")     # include all streams in sout
        media.add_option("no-sout-video")

        player = instance.media_player_new()
        player.set_media(media)

        done = threading.Event()

        def _on_end(event):
            done.set()

        def _on_err(event):
            done.set()

        em = player.event_manager()
        em.event_attach(vlc.EventType.MediaPlayerEndReached, _on_end)
        em.event_attach(vlc.EventType.MediaPlayerEncounteredError, _on_err)

        player.play()
        completed = done.wait(timeout=timeout)

        player.stop()
        player.release()
        media.release()
        return completed
    finally:
        instance.release()


def _sout_to_file(
    wav_path: Path,
    acodec: str,
    ab: int,
    mux: str,
    extra_transcode: str = "",
    timeout: float = 15.0,
) -> tuple[bool, Path]:
    """
    Transcode *wav_path* through a sout-to-file chain.

    Returns (completed, output_path).  Caller must delete output_path.
    """
    suffix = f".{mux}" if mux not in ("dummy", "raw") else ".bin"
    with tempfile.NamedTemporaryFile(suffix=suffix, delete=False) as f:
        out_path = Path(f.name)

    extra = f",{extra_transcode}" if extra_transcode else ""
    sout = (
        f"#transcode{{acodec={acodec},ab={ab},channels=2"
        f",samplerate=44100{extra}}}"
        f":std{{access=file,mux={mux},dst={out_path}}}"
    )
    completed = _play_sout(wav_path, sout, timeout=timeout)
    return completed, out_path


