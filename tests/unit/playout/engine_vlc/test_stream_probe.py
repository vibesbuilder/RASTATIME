"""
T9.2 — libVLC stream capability probe.

Answers the 8 open questions from STREAM_USE_CASES.md §9 empirically:

Q1  shout access_output module ships with the Windows VLC installer?
Q2  MP3 encoder is available (twolame / libavcodec)?
Q3  AAC encoder is available (FDK AAC / FFmpeg AAC)?
Q4  libVLC sout can produce OGG Opus in a container Icecast 2.4 accepts?
Q5  libVLC can inject ICY title metadata into an MP3 sout stream?
Q6  CPU / wall-clock overhead of 3 simultaneous encode-and-write chains?
Q7  shout module handles SHOUTcast v2 destination without crash?
Q8  Releasing + recreating a sout chain reconnects cleanly (no full restart)?

Tests are skipped when VLC is not installed.  All tests are read-only with
respect to the VLC installation; they write only temporary files under the
system temp directory.

Findings are collected into module-level RESULTS dict so a helper function
can dump them to STREAM_CAPABILITY_MATRIX.md (see --capture=no output).

IMPORTANT NOTE — Windows shout hang (Q1/Q8 extended tests)
-----------------------------------------------------------
On Windows with libVLC 3.x the shout access_output module does NOT fire an
error event when the target port refuses the connection.  VLC's internal
libshout connection attempt blocks indefinitely, and calling ``player.stop()``
after the event-wait timeout also blocks.  All shout-connection tests therefore
run cleanup in a daemon thread so they cannot hang the test-runner process.

This behaviour is itself a key Q8 finding: RASTATIME's StreamConnection
reconnect loop must use an external watchdog timer, NOT VLC error-event polling.
"""

