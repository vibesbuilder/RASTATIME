def _record(qid: str, available: bool, notes: str = "") -> None:
    """Record a finding into RESULTS."""
    RESULTS[qid] = {"available": available, "notes": notes}


def dump_capability_matrix() -> str:
    """
    Render RESULTS as a Markdown capability-matrix table.

    Call this in a test or via pytest --capture=no to see findings printed
    after the test run.
    """
    lines = [
        "# RASTATIME — libVLC Stream Capability Matrix",
        "",
        "Generated by T9.2 test suite (`tests/unit/playout/engine_vlc/test_stream_probe.py`).",
        "",
        "| Q | Capability | Available | Notes |",
        "|---|---|---|---|",
    ]
    labels = {
        "Q1": "shout access_output plugin",
        "Q2": "MP3 encoder (twolame / avcodec)",
        "Q3": "AAC encoder (FFmpeg mp4a)",
        "Q4a": "OGG Opus codec + muxer",
        "Q4b": "OGG Vorbis encode-to-file",
        "Q5": "ICY metadata injection",
        "Q6": "3 simultaneous sout chains",
        "Q7": "SHOUTcast v2 protocol support",
        "Q8a": "Error-event on connection refused",
        "Q8b": "Instance recreation after failure",
        "HLS": "HLS livehttp plugin",
        "DSHOW": "DirectShow capture (UC-I4)",
        "WASAPI": "WASAPI capture (UC-I4 alt.)",
    }
    for qid, label in labels.items():
        if qid in RESULTS:
            r = RESULTS[qid]
            tick = "✅" if r["available"] else "❌"
            notes = r.get("notes", "")
            lines.append(f"| {qid} | {label} | {tick} | {notes} |")
        else:
            lines.append(f"| {qid} | {label} | — | not tested |")
    return "\n".join(lines)

