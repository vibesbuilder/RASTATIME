# Q6 — CPU overhead of 3 simultaneous sout chains
# ---------------------------------------------------------------------------

@vlc_required
def test_q6_three_simultaneous_sout_chains_wall_clock():
    """
    Q6: Measure wall-clock time for 3 simultaneous encode-to-file chains
    (MP3 + OGG Vorbis + OGG Opus) running on a 0.5 s WAV input.

    Criterion: all three chains complete within 15 s (30× real-time headroom).
    Wall-clock time is printed for the capability matrix record.
    """
    import vlc

    wav = _make_wav(0.5)
    try:
        with tempfile.TemporaryDirectory() as tmpdir:
            chains = [
                (
                    "mp3",
                    f"#transcode{{acodec=mp3,ab=128,channels=2,samplerate=44100}}"
                    f":std{{access=file,mux=dummy,dst={Path(tmpdir)/'mp3_out.mp3'}}}",
                    Path(tmpdir) / "mp3_out.mp3",
                ),
                (
                    "vorb",
                    f"#transcode{{acodec=vorb,ab=128,channels=2,samplerate=44100}}"
                    f":std{{access=file,mux=ogg,dst={Path(tmpdir)/'ogg_out.ogg'}}}",
                    Path(tmpdir) / "ogg_out.ogg",
                ),
                (
                    "opus",
                    f"#transcode{{acodec=opus,ab=64,channels=2,samplerate=48000}}"
                    f":std{{access=file,mux=ogg,dst={Path(tmpdir)/'opus_out.opus.ogg'}}}",
                    Path(tmpdir) / "opus_out.opus.ogg",
                ),
            ]

            done_events = [threading.Event() for _ in chains]
            players = []
            instances = []

            for i, (name, sout, out_path) in enumerate(chains):
                inst = vlc.Instance("--no-video", "--quiet", "--aout=adummy")
                instances.append(inst)
                media = inst.media_new(wav.as_uri())
                media.add_option(f"sout={sout}")
                media.add_option("sout-all")
                media.add_option("no-sout-video")
                player = inst.media_player_new()
                player.set_media(media)
                players.append(player)

                ev = done_events[i]
                em = player.event_manager()
                em.event_attach(
                    vlc.EventType.MediaPlayerEndReached,
                    lambda e, ev=ev: ev.set(),
                )
                em.event_attach(
                    vlc.EventType.MediaPlayerEncounteredError,
                    lambda e, ev=ev: ev.set(),
                )

            t0 = time.monotonic()

            for player in players:
                player.play()

            # Wait for all three
            all_done = all(ev.wait(timeout=15.0) for ev in done_events)
            wall_time = time.monotonic() - t0

            for player in players:
                player.stop()
                player.release()
            for inst in instances:
                inst.release()

            print(
                f"\n[Q6] 3 simultaneous sout chains: "
                f"wall_time={wall_time:.3f}s, all_done={all_done}"
            )

            # Check all outputs exist and are non-empty
            for name, sout, out_path in chains:
                assert out_path.exists(), f"Output missing for {name}: {out_path}"
                assert out_path.stat().st_size > 0, f"Output empty for {name}"

            ok = all_done and wall_time < 5.0
            _record(
                "Q6",
                ok,
                f"3 chains: wall_time={wall_time:.3f}s, all_done={all_done}",
            )
            assert all_done, "Not all 3 chains completed within 15 s"
            # Wall-clock should not far exceed real-time; 3× headroom is generous
            assert wall_time < 5.0, (
                f"3 simultaneous chains took {wall_time:.2f}s (> 5s); "
                f"encoding is too slow on this machine"
            )
    finally:
        wav.unlink(missing_ok=True)


