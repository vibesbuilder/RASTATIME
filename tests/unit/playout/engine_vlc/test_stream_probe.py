# Q8 — Auto-reconnect behavior
# ---------------------------------------------------------------------------

@vlc_required
def test_q8_sout_to_nonexistent_server_fails_fast():
    """
    Q8: Probe whether VLC's shout module fires an error event quickly when
    the target server refuses the connection.

    FINDING (Windows, libVLC 3.x):
        VLC does NOT fire an error/end event within 8 s.  The shout module
        blocks indefinitely in its connection attempt.  ``player.stop()``
        also blocks in the same situation, so cleanup runs in a daemon thread.

    IMPLICATION for RASTATIME:
        ``StreamConnection`` must use an *external watchdog timer*, not VLC
        error-event polling, to detect and recover from a dropped Icecast link.
    """
    import vlc

    wav = _make_wav(0.3)
    instance = vlc.Instance("--no-video", "--quiet", "--aout=adummy")
    try:
        sout = (
            "#transcode{acodec=mp3,ab=128}"
            ":std{access=shout,mux=dummy,dst=source:pass@127.0.0.1:19432/test.mp3}"
        )
        media = instance.media_new(wav.as_uri())
        media.add_option(f"sout={sout}")

        player = instance.media_player_new()
        player.set_media(media)

        error_or_end = threading.Event()
        em = player.event_manager()
        em.event_attach(
            vlc.EventType.MediaPlayerEncounteredError,
            lambda e: error_or_end.set(),
        )
        em.event_attach(
            vlc.EventType.MediaPlayerEndReached,
            lambda e: error_or_end.set(),
        )

        t0 = time.monotonic()
        player.play()
        fired = error_or_end.wait(timeout=5.0)
        elapsed = time.monotonic() - t0

        print(
            f"\n[Q8a] event_fired={fired}, elapsed={elapsed:.3f}s"
            f"\n[Q8a] FINDING: VLC shout does {'NOT ' if not fired else ''}fail fast on this platform."
        )

        # Cleanup in daemon thread — player.stop() blocks when shout is stuck.
        def _cleanup():
            try:
                player.stop()
                player.release()
                media.release()
                instance.release()
            except Exception:
                pass
        t_cleanup = threading.Thread(target=_cleanup, daemon=True)
        t_cleanup.start()
        t_cleanup.join(timeout=2.0)  # best-effort; don't block the runner

        _record(
            "Q8a",
            fired,
            (
                f"error event in {elapsed:.2f}s"
                if fired
                else "no error event within 5 s — use watchdog for reconnect"
            ),
        )
    finally:
        wav.unlink(missing_ok=True)

    # We do NOT assert fired=True here: the absence of an error event is itself
    # a valid (and important) finding.  The test passes either way so the
    # capability matrix can record the actual platform behaviour.
    assert True, (
        "[Q8a] Finding recorded: see RESULTS['Q8a'] and capability matrix."
    )


