"""
T19.1 — Normalized playback event record (domain layer).

``PlaybackEvent`` is the canonical, normalized representation of a single
completed or in-progress playback.  It is:

* **Pure Python** — no Django, no database, no I/O dependency.
* **Frozen dataclass** — immutable once created; safe to pass across threads.
* **Self-contained** — all human-readable fields are denormalized so the
  record remains readable even if the source file or show is later deleted.

Lifecycle
---------
A ``PlaybackEvent`` is created from a :class:`~.HistoryEntry` (the
in-memory ring-buffer record) via :meth:`PlaybackEvent.from_history_entry`.
It is then passed to the persistence layer (``libretime_api.playback``)
which stores it in the ``rastatime_playback_event`` table.

Source-type inference
----------------------
:meth:`PlaybackEvent.from_history_entry` calls
:func:`infer_source_type` to classify the item URI:

============  =========================
source_type   URI pattern
============  =========================
``file``      ``file://`` or bare path
``webstream`` ``http://`` / ``https://``
``linein``    ``linein://``
``live``      any other non-empty URI
``unknown``   empty URI
============  =========================
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Optional

if TYPE_CHECKING:
    from ._history import HistoryEntry


# ---------------------------------------------------------------------------
# Source-type constants
# ---------------------------------------------------------------------------

class PlaybackSourceType:
    """String constants for the ``source_type`` field."""

    FILE      = "file"
    WEBSTREAM = "webstream"
    LINEIN    = "linein"
    LIVE      = "live"
    UNKNOWN   = "unknown"

    _ALL = frozenset({FILE, WEBSTREAM, LINEIN, LIVE, UNKNOWN})

    @classmethod
    def is_valid(cls, value: str) -> bool:
        """Return *True* if *value* is a recognised source type."""
        return value in cls._ALL


# ---------------------------------------------------------------------------
# Source-type inference
# ---------------------------------------------------------------------------

def infer_source_type(uri: str) -> str:
    """
    Classify a playback URI into a :class:`PlaybackSourceType` constant.

    Parameters
    ----------
    uri:
        The URI string from :attr:`~playout.engine_interface.QueueItem.uri`.
        May be empty.

    Returns
    -------
    str
        One of the :class:`PlaybackSourceType` constants.
    """
    if not uri:
        return PlaybackSourceType.UNKNOWN
    lower = uri.lower()
    if lower.startswith("file://") or (
        not lower.startswith(("http://", "https://", "linein://"))
        and ("/" in uri or "\\" in uri)
    ):
        return PlaybackSourceType.FILE
    if lower.startswith(("http://", "https://")):
        return PlaybackSourceType.WEBSTREAM
    if lower.startswith("linein://"):
        return PlaybackSourceType.LINEIN
    return PlaybackSourceType.LIVE


# ---------------------------------------------------------------------------
# PlaybackEvent — the normalized domain record
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class PlaybackEvent:
    """
    Normalized, immutable record of a single playback occurrence.

    All human-readable fields (``title``, ``artist``) are denormalized from
    the source item at the time of playback.  This ensures history remains
    readable even if the underlying file or show record is deleted.

    Parameters
    ----------
    event_id:
        UUID string that uniquely identifies this playback event.
        Generated by :meth:`from_history_entry` via ``uuid.uuid4()``.
    source_type:
        Classification of the media source — one of the
        :class:`PlaybackSourceType` constants.
    item_id:
        The :attr:`~playout.engine_interface.QueueItem.id` of the item that
        was played.  Stable for the duration of the item's lifetime in the
        queue; may not be globally unique across restarts.
    title:
        Denormalized track or stream title.  Empty string when unknown.
    artist:
        Denormalized artist name.  Empty string when unknown.
    uri:
        Original URI of the media (file path or stream URL).
        Empty string for line-in sources that have no URI.
    started_at:
        UTC datetime when playback of this item began.
        Always timezone-aware.
    ended_at:
        UTC datetime when playback of this item ended.
        *None* while the item is still playing.
    metadata:
        Raw metadata dict from
        :attr:`~playout.engine_interface.QueueItem.metadata`.
        Stored as-is for future use; not interpreted by the domain model.
    """

    event_id:    str
    source_type: str
    item_id:     str
    title:       str
    artist:      str
    uri:         str
    started_at:  datetime
    ended_at:    Optional[datetime] = None
    metadata:    dict = field(default_factory=dict, compare=False, hash=False)

    # ------------------------------------------------------------------
    # Computed properties
    # ------------------------------------------------------------------

    @property
    def duration_played(self) -> Optional[float]:
        """
        Seconds between :attr:`started_at` and :attr:`ended_at`.

        Returns *None* while the event is still in progress
        (:attr:`ended_at` is *None*).  Always non-negative.
        """
        if self.ended_at is None:
            return None
        delta = (self.ended_at - self.started_at).total_seconds()
        return max(0.0, delta)

    @property
    def is_completed(self) -> bool:
        """*True* when :attr:`ended_at` has been set."""
        return self.ended_at is not None

    # ------------------------------------------------------------------
    # Serialisation
    # ------------------------------------------------------------------

    def to_dict(self) -> dict:
        """
        Serialise to a plain ``dict`` suitable for JSON responses.

        All datetime values are ISO-8601 strings.  ``duration_played``
        is included as a convenience for API consumers.
        """
        return {
            "event_id":       self.event_id,
            "source_type":    self.source_type,
            "item_id":        self.item_id,
            "title":          self.title,
            "artist":         self.artist,
            "uri":            self.uri,
            "started_at":     self.started_at.isoformat(),
            "ended_at":       self.ended_at.isoformat() if self.ended_at else None,
            "duration_played": self.duration_played,
        }

    # ------------------------------------------------------------------
    # Factory — from in-memory HistoryEntry
    # ------------------------------------------------------------------

    @classmethod
    def from_history_entry(
        cls,
        entry: "HistoryEntry",
        *,
        event_id: Optional[str] = None,
    ) -> "PlaybackEvent":
        """
        Construct a ``PlaybackEvent`` from an in-memory
        :class:`~.HistoryEntry`.

        Parameters
        ----------
        entry:
            A completed or in-progress history entry from
            :class:`~.PlayoutHistoryLogger`.
        event_id:
            Override the generated UUID string.  Useful in tests.
            When *None* (the default), a fresh ``uuid4()`` is generated.

        Returns
        -------
        PlaybackEvent
            Normalized, immutable playback event record.
        """
        item = entry.item
        return cls(
            event_id=event_id if event_id is not None else str(uuid.uuid4()),
            source_type=infer_source_type(item.uri),
            item_id=item.id,
            title=item.title or "",
            artist=item.artist or "",
            uri=item.uri or "",
            started_at=entry.started_at,
            ended_at=entry.ended_at,
            metadata=dict(item.metadata),
        )
