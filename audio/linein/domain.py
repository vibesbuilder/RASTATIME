"""
LineIn — pure domain model for a configured local line-in source.

This module is Django-free: it can be imported and tested without a
database or running application server.  The Django persistence layer
lives in ``backend/api/rastatime_api/linein/models.py``, which bridges
between this domain model and the ORM via :meth:`to_domain` /
:meth:`update_from_domain`.

Relationship to SoundcardSettings
----------------------------------
:class:`~audio.soundcard.settings_model.SoundcardSettings` carried a
lightweight ``line_in_device_ids`` placeholder (a tuple of stable IDs).
T14.1 replaces that placeholder with proper :class:`LineIn` entities,
each of which has a stable UUID, a human name, a device reference, a
channel mapping, an enable flag, a description, and a priority.

Design
------
``LineIn`` is an *immutable* frozen dataclass.  State changes always
produce a new instance via ``with_*`` builder methods, matching the
pattern used by :class:`~audio.soundcard.settings_model.SoundcardSettings`.

Fields
------
id : str
    UUID string (e.g. ``"a1b2c3d4-e5f6-7890-ab12-cd34ef567890"``).
    Generated by :meth:`create`; must be stable across reboots.
name : str
    Human-readable label (e.g. ``"Drum Kit"``, ``"Interview Mic"``).
    Must not be blank.
device_id : str
    :attr:`~audio.soundcard.interface.AudioDevice.stable_id` of the
    underlying Windows audio input endpoint.  Must not be blank.
channel_mapping : tuple[int, ...]
    0-based indices of the channels to capture on the device.
    ``(0, 1)`` means "stereo, channels 1 & 2"; ``(0,)`` means mono.
    Must be non-empty; all elements must be non-negative integers.
enabled : bool
    Whether this line-in is active and should be offered for routing.
    Defaults to ``True``.
description : str
    Optional free-text description.  Defaults to ``""``.
priority : int
    Higher integer = higher priority when multiple line-ins compete for
    the same playout slot.  Defaults to ``0``.
input_gain_db : float
    Static input gain in dB the playout applies to this line-in on air
    (RASTATIME 2026-10-02).  ``-20.0`` to ``+20.0``, default ``0.0``.

Validation
----------
All validation runs in ``__post_init__`` and is therefore enforced on
every construction path, including ``from_dict`` and the ``with_*`` builders.
Constructing an invalid instance always raises ``ValueError`` or ``TypeError``.

UUID note
---------
The ``id`` field is a plain string, not a :class:`uuid.UUID`.  Callers
must not rely on format beyond "non-empty unique string".  Use
:meth:`create` (which calls ``str(uuid.uuid4())``) rather than
constructing IDs manually.
"""

from __future__ import annotations

import math
import uuid as _uuid_mod
from dataclasses import dataclass, field
from typing import Optional

# RASTATIME 2026-10-02 - accepted range of LineIn.input_gain_db, the same
# as the webstream input gain (WebstreamController clamps to it).
INPUT_GAIN_DB_MIN = -20.0
INPUT_GAIN_DB_MAX = 20.0


@dataclass(frozen=True)
class LineIn:
    """
    Immutable entity representing one configured local line-in input.

    Prefer :meth:`create` for new instances (it auto-generates the UUID).
    Prefer :meth:`from_dict` to reconstruct from persisted data.
    Prefer the ``with_*`` builder methods for all state changes.
    """

    id: str
    """UUID string that uniquely identifies this line-in entity."""

    name: str
    """Human-readable display name (e.g. ``"Drum Kit"``).  Must not be blank."""

    device_id: str
    """
    Stable ID of the underlying audio input device (matches
    :attr:`~audio.soundcard.interface.AudioDevice.stable_id`).
    Must not be blank.
    """

    channel_mapping: tuple[int, ...]
    """
    0-based channel indices to capture from the device.
    ``(0, 1)`` = stereo channels 1 & 2; ``(0,)`` = mono channel 1.
    Must be non-empty; all elements must be ``>= 0``.
    """

    enabled: bool = True
    """``True`` if this line-in is active and available for routing."""

    description: str = ""
    """Optional free-text description.  May be empty."""

    priority: int = 0
    """
    Routing priority.  Higher integer wins when multiple line-ins compete
    for the same playout slot.  Must be a plain integer (no upper bound).
    """

    length_seconds: Optional[int] = None
    """
    RASTATIME 2026-05-12 — default duration (in seconds) used when this
    line-in is added to a show from the Media Library.  ``None`` means
    "fall back to 1800 s = 30 minutes", matching the Webstream Library
    default in :meth:`WebstreamController.newAction`.
    """

    device_name: str = ""
    """
    RASTATIME 2026-05-14 — B.4 #4 UUID-Wechsel nach Reboot.

    OS-reported friendly name of the audio input endpoint at save time
    (e.g. ``"Mikrofon (Jabra Speak 410 USB)"``).  Used as a fallback
    when :attr:`device_id` (the WASAPI endpoint GUID) no longer
    resolves to an active device, which can happen across reboots for
    USB audio gear.  Empty string means "no fallback name available"
    (legacy rows pre-dating the field) — the resolver then behaves
    exactly as before, surfacing preflight warnings until the operator
    re-saves the device picker once.

    Positioned after the other defaulted fields so existing call sites
    that pass kwargs continue to work without changes.
    """

    input_gain_db: float = 0.0
    """
    RASTATIME 2026-10-02 - static input gain in dB, the line-in
    counterpart of ``cc_webstream.input_gain_db``.  The playout applies
    it on air as a linear ``amplify`` factor in Liquidsoap (``var.set
    linein.gain``), so the studio level can be trimmed to the station
    loudness without touching the mixer.  ``-20.0`` to ``+20.0``;
    ``0.0`` = unchanged.
    """

    # ------------------------------------------------------------------
    # Validation
    # ------------------------------------------------------------------

    def __post_init__(self) -> None:
        if not isinstance(self.name, str) or not self.name.strip():
            raise ValueError("LineIn.name must be a non-empty string")
        if not isinstance(self.device_id, str) or not self.device_id.strip():
            raise ValueError("LineIn.device_id must be a non-empty string")
        if not isinstance(self.device_name, str):
            raise TypeError("LineIn.device_name must be a string (may be empty)")
        if not isinstance(self.channel_mapping, tuple) or len(self.channel_mapping) == 0:
            raise ValueError("LineIn.channel_mapping must be a non-empty tuple")
        # RASTATIME 2026-08-31 — the capture layer produces a stereo
        # signal from at most two source channels (a pair, or one
        # channel duplicated to both lanes).  Longer mappings were
        # never applied by any runtime; reject them at the boundary so
        # the UI/API surface matches what playout can actually do.
        if len(self.channel_mapping) > 2:
            raise ValueError(
                "LineIn.channel_mapping supports 1 (mono) or 2 (stereo) "
                f"channels, got {len(self.channel_mapping)}"
            )
        for idx, ch in enumerate(self.channel_mapping):
            if not isinstance(ch, int):
                raise TypeError(
                    f"LineIn.channel_mapping[{idx}] must be an int, "
                    f"got {type(ch).__name__!r}"
                )
            if ch < 0:
                raise ValueError(
                    f"LineIn.channel_mapping[{idx}] must be >= 0, got {ch!r}"
                )
        if not isinstance(self.priority, int):
            raise TypeError("LineIn.priority must be an int")
        if self.length_seconds is not None:
            if not isinstance(self.length_seconds, int) or self.length_seconds < 0:
                raise ValueError(
                    "LineIn.length_seconds must be None or a non-negative int"
                )
        if (
            not isinstance(self.input_gain_db, (int, float))
            or isinstance(self.input_gain_db, bool)
        ):
            raise TypeError("LineIn.input_gain_db must be a number")
        if (
            not math.isfinite(self.input_gain_db)
            or not INPUT_GAIN_DB_MIN <= self.input_gain_db <= INPUT_GAIN_DB_MAX
        ):
            raise ValueError(
                f"LineIn.input_gain_db must be between {INPUT_GAIN_DB_MIN:+.0f} "
                f"and {INPUT_GAIN_DB_MAX:+.0f} dB, got {self.input_gain_db!r}"
            )

    # ------------------------------------------------------------------
    # Factory
    # ------------------------------------------------------------------

    @classmethod
    def create(
        cls,
        *,
        name: str,
        device_id: str,
        channel_mapping: tuple[int, ...] | list[int],
        enabled: bool = True,
        description: str = "",
        priority: int = 0,
        length_seconds: Optional[int] = None,
        device_name: str = "",
        input_gain_db: float = 0.0,
    ) -> "LineIn":
        """
        Create a new :class:`LineIn` with an auto-generated UUID.

        Parameters
        ----------
        name:
            Human-readable display name.  Must not be blank.
        device_id:
            Stable ID of the audio input device.  Must not be blank.
        channel_mapping:
            Sequence of 0-based channel indices.  Accepts any iterable
            of ints; stored internally as a tuple.  Must be non-empty;
            all elements must be ``>= 0``.
        enabled:
            Whether this line-in is initially active (default ``True``).
        description:
            Optional free-text description (default ``""``).
        priority:
            Routing priority (default ``0``).
        length_seconds:
            Default Library duration in seconds (default ``None`` →
            1800 s / 30 min fallback at consumption sites).
        input_gain_db:
            Static input gain in dB (default ``0.0``).

        Returns
        -------
        LineIn
            A new immutable :class:`LineIn` with a freshly generated UUID.
        """
        return cls(
            id=str(_uuid_mod.uuid4()),
            name=name,
            device_id=device_id,
            channel_mapping=tuple(channel_mapping),
            enabled=enabled,
            description=description,
            priority=priority,
            length_seconds=length_seconds,
            device_name=device_name,
            input_gain_db=input_gain_db,
        )

    # ------------------------------------------------------------------
    # Immutable builders
    # ------------------------------------------------------------------

    def with_name(self, name: str) -> "LineIn":
        """Return a new instance with ``name`` replaced."""
        return LineIn(
            id=self.id, name=name, device_id=self.device_id,
            channel_mapping=self.channel_mapping, enabled=self.enabled,
            description=self.description, priority=self.priority,
            length_seconds=self.length_seconds,
            device_name=self.device_name,
            input_gain_db=self.input_gain_db,
        )

    def with_device_id(self, device_id: str) -> "LineIn":
        """Return a new instance with ``device_id`` replaced."""
        return LineIn(
            id=self.id, name=self.name, device_id=device_id,
            channel_mapping=self.channel_mapping, enabled=self.enabled,
            description=self.description, priority=self.priority,
            length_seconds=self.length_seconds,
            device_name=self.device_name,
            input_gain_db=self.input_gain_db,
        )

    def with_channel_mapping(
        self, channel_mapping: tuple[int, ...] | list[int]
    ) -> "LineIn":
        """
        Return a new instance with ``channel_mapping`` replaced.

        Accepts a list for convenience; stored as a tuple.
        """
        return LineIn(
            id=self.id, name=self.name, device_id=self.device_id,
            channel_mapping=tuple(channel_mapping), enabled=self.enabled,
            description=self.description, priority=self.priority,
            length_seconds=self.length_seconds,
            device_name=self.device_name,
            input_gain_db=self.input_gain_db,
        )

    def with_enabled(self, enabled: bool) -> "LineIn":
        """Return a new instance with the ``enabled`` flag set."""
        return LineIn(
            id=self.id, name=self.name, device_id=self.device_id,
            channel_mapping=self.channel_mapping, enabled=enabled,
            description=self.description, priority=self.priority,
            length_seconds=self.length_seconds,
            device_name=self.device_name,
            input_gain_db=self.input_gain_db,
        )

    def with_description(self, description: str) -> "LineIn":
        """Return a new instance with ``description`` replaced."""
        return LineIn(
            id=self.id, name=self.name, device_id=self.device_id,
            channel_mapping=self.channel_mapping, enabled=self.enabled,
            description=description, priority=self.priority,
            length_seconds=self.length_seconds,
            device_name=self.device_name,
            input_gain_db=self.input_gain_db,
        )

    def with_priority(self, priority: int) -> "LineIn":
        """Return a new instance with ``priority`` replaced."""
        return LineIn(
            id=self.id, name=self.name, device_id=self.device_id,
            channel_mapping=self.channel_mapping, enabled=self.enabled,
            description=self.description, priority=priority,
            length_seconds=self.length_seconds,
            device_name=self.device_name,
            input_gain_db=self.input_gain_db,
        )

    def with_length_seconds(self, length_seconds: Optional[int]) -> "LineIn":
        """Return a new instance with ``length_seconds`` replaced."""
        return LineIn(
            id=self.id, name=self.name, device_id=self.device_id,
            channel_mapping=self.channel_mapping, enabled=self.enabled,
            description=self.description, priority=self.priority,
            length_seconds=length_seconds,
            device_name=self.device_name,
            input_gain_db=self.input_gain_db,
        )

    def with_device_name(self, device_name: str) -> "LineIn":
        """Return a new instance with ``device_name`` replaced.

        RASTATIME 2026-05-14 — used when the playout's resolver has
        successfully fallen back to a name-match and persists the new
        device_id / device_name pair, so subsequent boots don't have
        to re-fall back.
        """
        return LineIn(
            id=self.id, name=self.name, device_id=self.device_id,
            channel_mapping=self.channel_mapping, enabled=self.enabled,
            description=self.description, priority=self.priority,
            length_seconds=self.length_seconds,
            device_name=device_name,
            input_gain_db=self.input_gain_db,
        )

    def with_input_gain_db(self, input_gain_db: float) -> "LineIn":
        """Return a new instance with ``input_gain_db`` replaced."""
        return LineIn(
            id=self.id, name=self.name, device_id=self.device_id,
            channel_mapping=self.channel_mapping, enabled=self.enabled,
            description=self.description, priority=self.priority,
            length_seconds=self.length_seconds,
            device_name=self.device_name,
            input_gain_db=input_gain_db,
        )

    # ------------------------------------------------------------------
    # Serialisation
    # ------------------------------------------------------------------

    def to_dict(self) -> dict:
        """
        Convert to a JSON-serialisable dict.

        Returns
        -------
        dict
            Keys: ``id``, ``name``, ``device_id``, ``channel_mapping``
            (as a plain list), ``enabled``, ``description``, ``priority``.
        """
        return {
            "id":              self.id,
            "name":            self.name,
            "device_id":       self.device_id,
            "device_name":     self.device_name,
            "channel_mapping": list(self.channel_mapping),
            "enabled":         self.enabled,
            "description":     self.description,
            "priority":        self.priority,
            "length_seconds":  self.length_seconds,
            "input_gain_db":   self.input_gain_db,
        }

    @classmethod
    def from_dict(cls, data: dict) -> "LineIn":
        """
        Reconstruct a :class:`LineIn` from a dict (e.g. from persisted JSON).

        Required keys: ``id``, ``name``, ``device_id``, ``channel_mapping``.
        Optional keys: ``enabled`` (default ``True``), ``description``
        (default ``""``), ``priority`` (default ``0``).
        Extra keys are ignored.

        Raises
        ------
        KeyError
            If any required key is missing from *data*.
        ValueError, TypeError
            If a field value fails domain validation.
        """
        return cls(
            id=data["id"],
            name=data["name"],
            device_id=data["device_id"],
            channel_mapping=tuple(data["channel_mapping"]),
            enabled=data.get("enabled", True),
            description=data.get("description", ""),
            priority=data.get("priority", 0),
            length_seconds=data.get("length_seconds"),
            device_name=data.get("device_name", ""),
            input_gain_db=data.get("input_gain_db", 0.0),
        )
